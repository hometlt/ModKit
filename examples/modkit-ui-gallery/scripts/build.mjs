/**
 * Build the gallery into `dist/`, then optionally serve it.
 *
 *   node scripts/build.mjs           build
 *   node scripts/build.mjs --serve   build and serve on 8730
 *
 * The catalog snapshot is derived from the generated UK-A catalog in `references/modkit-docs`.
 * When that checkout is absent the snapshot records the reason and the gallery says so — it never
 * invents component rows.
 */
import { build } from 'esbuild'
import { format, resolveConfig } from 'prettier'
import { createServer } from 'node:http'
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, extname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  discoverTextDataEntrypoints,
  relativeEntrypointSpecifier,
} from '../../../scripts/text-data-entrypoints.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const galleryRoot = resolve(here, '..')
const repoRoot = resolve(galleryRoot, '..', '..')
const dist = join(galleryRoot, 'dist')

// ---------------------------------------------------------------- catalog snapshot
const catalogPath = resolve(
  repoRoot,
  '..',
  'references',
  'modkit-docs',
  'MK3',
  'uk-a',
  'component-catalog.md',
)
const snapshotPath = join(galleryRoot, 'src', 'catalog-snapshot.json')

function buildSnapshot() {
  if (!existsSync(catalogPath)) {
    return {
      reason:
        'Generated component catalog not found (expected ' +
        '../references/modkit-docs/MK3/uk-a/component-catalog.md). No rows are fabricated.',
      rows: [],
    }
  }
  const markdown = readFileSync(catalogPath, 'utf8')
  const rows = []
  let kind = 'unknown'
  for (const line of markdown.split(/\r?\n/)) {
    const heading = line.match(/^## ([a-z-]+)\s*$/u)
    if (heading) {
      kind = heading[1]
      continue
    }
    const row = line.match(/^\|\s*`([^`]+)`\s*\|\s*([^|]+?)\s*\|\s*`([^`]+)`\s*\|/u)
    if (row && kind !== 'unknown') {
      rows.push({ id: row[1], name: row[2], kind, status: row[3] })
    }
  }
  return { source: 'modkitx/docs/MK3/uk-a/component-catalog.md', rows }
}

const snapshot = buildSnapshot()
writeFileSync(snapshotPath, `${JSON.stringify(snapshot, null, 2)}\n`)
console.log(
  snapshot.rows.length > 0
    ? `catalog snapshot: ${snapshot.rows.length} rows`
    : `catalog snapshot: unavailable — ${snapshot.reason}`,
)

// ---------------------------------------------------------------- text-data entrypoints
// The contribution manifest is the authority for entrypoints, not a hardcoded path. We read the
// declared entrypoints and import only the ones that exist, so a half-migrated extension degrades
// with a named reason instead of failing the whole bundle.
const FORMAT_IDS = ['json', 'jsonc', 'xml', 'yaml', 'toml', 'ini', 'csv', 'tsv']
const entrypoints = discoverTextDataEntrypoints(repoRoot, FORMAT_IDS)
const usable = entrypoints.filter(entry => entry.absolute !== undefined)
const broken = entrypoints.filter(entry => entry.absolute === undefined)

const importName = entry => `${entry.kind}_${entry.id.replace(/-/gu, '_')}`
const generatedEntrypointsPath = join(galleryRoot, 'src', 'text-data-entrypoints.generated.ts')
const generated = [
  '/* Generated by examples/modkit-ui-gallery/scripts/build.mjs - do not edit. */',
  '/* Entrypoints come from the text-data contribution manifests, never from hardcoded paths. */',
  '',
  ...usable.map(
    entry =>
      `import { ${entry.kind === 'codec' ? 'createCodec' : 'createProvider'} as ${importName(entry)} } from '${relativeEntrypointSpecifier(generatedEntrypointsPath, entry.absolute)}'`,
  ),
  '',
  'export const TEXT_DATA_ENTRYPOINTS: Readonly<Record<string, unknown>> = Object.freeze({',
  ...usable.map(entry => `  '${entry.kind}:${entry.id}': ${importName(entry)},`),
  '})',
  '',
  'export interface BrokenEntrypoint {',
  '  readonly id: string',
  '  readonly kind: string',
  '  readonly reason: string',
  '}',
  '',
  'export const TEXT_DATA_BROKEN: readonly BrokenEntrypoint[] = Object.freeze([',
  ...broken.map(
    entry =>
      `  { id: '${entry.id}', kind: '${entry.kind}', reason: ${JSON.stringify(entry.reason)} },`,
  ),
  '])',
  '',
].join(String.fromCharCode(10))
const prettierConfig = (await resolveConfig(galleryRoot)) ?? {}
writeFileSync(
  generatedEntrypointsPath,
  await format(generated, { ...prettierConfig, parser: 'typescript' }),
)
console.log(
  broken.length === 0
    ? `text-data entrypoints: ${usable.length} resolved`
    : `text-data entrypoints: ${usable.length} resolved, ${broken.length} BROKEN -> ${broken.map(e => `${e.kind}:${e.id}`).join(', ')}`,
)

// ---------------------------------------------------------------- bundle
mkdirSync(dist, { recursive: true })

await build({
  entryPoints: [join(galleryRoot, 'src', 'main.ts')],
  outfile: join(dist, 'main.js'),
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: ['chrome120', 'firefox121', 'safari17'],
  absWorkingDir: repoRoot,
  // Monaco ships CSS and font assets; the CSS is extracted to a sibling file the page links,
  // which is what lets the editor render at all under `style-src 'self'`.
  loader: { '.ttf': 'dataurl', '.css': 'css' },
  logLevel: 'warning',
})

// Monaco runs its language services in workers and asks the host for them through
// `MonacoEnvironment`. Supplying them is the composition root's job, not the viewer's: the editor
// extension must not know a bundler's output paths (doc 19 §4). Without these the editor still
// paints and tokenises, but every worker request throws and JSON validation silently never runs.
// monaco-editor is a dependency of the editor extension, not of the repo root, so a bare specifier
// does not resolve from `absWorkingDir`. Point at the files and say so plainly if they move.
const monacoRoot = resolve(repoRoot, 'packages/code/node_modules/monaco-editor/esm/vs')
const workerEntries = {
  'editor.worker': join(monacoRoot, 'editor', 'editor.worker.js'),
  'json.worker': join(monacoRoot, 'language', 'json', 'json.worker.js'),
}
for (const [name, path] of Object.entries(workerEntries)) {
  if (!existsSync(path)) {
    console.error(`missing Monaco worker entry for ${name}: ${path}`)
    process.exit(1)
  }
}

await build({
  entryPoints: workerEntries,
  outdir: dist,
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome120', 'firefox121', 'safari17'],
  absWorkingDir: repoRoot,
  logLevel: 'warning',
})
console.log('monaco workers: editor, json')

const stylesheet = join(repoRoot, 'packages', 'ui', 'styles', 'modkit-ui.css')
if (!existsSync(stylesheet)) {
  console.error(
    'missing packages/ui/styles/modkit-ui.css — run pnpm --filter @modkitx-x3/ui tokens:emit',
  )
  process.exit(1)
}
cpSync(stylesheet, join(dist, 'modkit-ui.css'))
// The gallery shares the application mark so a pinned tab is recognisable next to the real apps.
cpSync(join(repoRoot, 'apps', 'web', 'public', 'favicon-32.png'), join(dist, 'favicon-32.png'))
// ---------------------------------------------------------------- C1/C2 static gate
// The page policy is relaxed for the trusted editor, so it can no longer prove that our own
// components avoid the forbidden mechanisms. Prove it at the source instead, where the editor's
// vendored bundle is not in scope.
{
  const C1 = /\.setAttribute\(\s*['"`]style['"`]/u
  const C2 = /createElement\(\s*['"`]style['"`]/u
  const roots = [
    resolve(repoRoot, 'packages/ui/src'),
    resolve(repoRoot, 'examples/modkit-ui-gallery/src'),
  ]
  const offences = []
  const walk = dir => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name)
      if (entry.isDirectory()) {
        walk(path)
        continue
      }
      if (!/\.(?:ts|js)$/u.test(entry.name)) continue
      const body = readFileSync(path, 'utf8')
      // The probe's whole purpose is to attempt them, so it is the one allowed caller.
      if (path.endsWith(join('src', 'main.ts'))) continue
      if (C1.test(body)) offences.push(`${path}: C1 — setAttribute('style')`)
      if (C2.test(body)) offences.push(`${path}: C2 — createElement('style')`)
    }
  }
  for (const root of roots) if (existsSync(root)) walk(root)
  if (offences.length > 0) {
    console.error(`C1/C2 gate FAILED with ${offences.length} offence(s):`)
    for (const offence of offences) console.error(`  - ${offence}`)
    process.exit(1)
  }
  console.log('C1/C2 static gate: clean')
}

// The served policy arrives as a header, which page script cannot read. Stamp the exact text the
// server will send so the CSP probe asserts against the policy actually in force, not a guess.
const { VIEWER_CSP_TRUSTED_EDITOR_TEXT } = await import('@modkitx-x3/ui/viewer')
writeFileSync(
  join(dist, 'index.html'),
  readFileSync(join(galleryRoot, 'index.html'), 'utf8').replace(
    '<html ',
    `<html data-mk-csp="${VIEWER_CSP_TRUSTED_EDITOR_TEXT.replaceAll('"', '&quot;')}" `,
  ),
)
cpSync(join(galleryRoot, 'gallery.css'), join(dist, 'gallery.css'))
// esbuild emits the extracted stylesheet next to the bundle; the page links it explicitly.
if (existsSync(join(dist, 'main.css'))) console.log('monaco stylesheet extracted')
console.log(`built ${dist}`)

// ---------------------------------------------------------------- optional server
if (process.argv.includes('--serve')) {
  const types = {
    '.html': 'text/html',
    '.js': 'text/javascript',
    '.css': 'text/css',
    '.json': 'application/json',
  }
  const port = 8730
  // The gallery embeds the trusted Monaco backend, so it serves VIEWER_CSP_TRUSTED_EDITOR —
  // strict everywhere except `style-src 'unsafe-inline'`, which Monaco's injected theme needs.
  // Untrusted viewers keep the strict VIEWER_CSP; this relaxation does not reach them.
  const { VIEWER_CSP_TRUSTED_EDITOR: VIEWER_CSP } = await import('@modkitx-x3/ui/viewer')
  const policy = () => {
    const directives = Object.entries(VIEWER_CSP).map(([name, value]) => {
      const kebab = name.replace(/[A-Z]/gu, match => `-${match.toLowerCase()}`)
      return `${kebab} ${value}`
    })
    // Every directive comes from the exported policy. Appending one here is how the served page
    // last drifted from the contract it claims to test.
    return directives.join('; ')
  }

  createServer((request, response) => {
    const url = new URL(request.url ?? '/', `http://localhost:${port}`)
    const name = url.pathname === '/' ? '/index.html' : url.pathname
    const file = join(dist, name)
    if (!file.startsWith(dist) || !existsSync(file)) {
      response.writeHead(404)
      response.end('not found')
      return
    }
    response.writeHead(200, {
      'Content-Type': types[extname(file)] ?? 'application/octet-stream',
      'Content-Security-Policy': policy(),
    })
    response.end(readFileSync(file))
  }).listen(port, () => console.log(`gallery on http://localhost:${port}/  (strict policy)`))
}
