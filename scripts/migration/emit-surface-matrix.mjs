#!/usr/bin/env node
// Inventory-derived format × surface projection. Core is the default input. Owner repositories
// may be added only explicitly: `--root label=<absolute path>` for an intentional live source or
// `--snapshot label=<absolute git repository>@<40-char commit>` for an immutable Git-ODB view.
// Both --root and --snapshot are repeatable; --check compares the generated JSON and Markdown.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'
import { SURFACE_ANCHORS, buildSurfaceMatrix, loadInventorySources } from './lib/surface-matrix.mjs'

const repoRoot = path.resolve(fileURLToPath(new URL('../..', import.meta.url)))
const args = process.argv.slice(2)
const check = args.includes('--check')
const quiet = args.includes('--quiet')
const values = flag =>
  args.flatMap((value, index) => (value === flag ? [args[index + 1]] : [])).filter(Boolean)
const value = flag => values(flag).at(-1)
const parseLabeledPath = raw => {
  const split = raw.indexOf('=')
  if (split <= 0 || split === raw.length - 1)
    throw new Error(`${raw}: expected label=absolute-path`)
  const rawDirectory = raw.slice(split + 1)
  if (!path.isAbsolute(rawDirectory)) throw new Error(`${raw}: path must be absolute`)
  const directory = path.resolve(rawDirectory)
  return { label: raw.slice(0, split), directory }
}
const parseSnapshot = raw => {
  const split = raw.indexOf('=')
  const at = raw.lastIndexOf('@')
  if (split <= 0 || at <= split + 1 || at === raw.length - 1)
    throw new Error(`${raw}: expected label=absolute-repository@40-character-commit`)
  const rawRepository = raw.slice(split + 1, at)
  if (!path.isAbsolute(rawRepository)) throw new Error(`${raw}: repository must be absolute`)
  const repository = path.resolve(rawRepository)
  return { label: raw.slice(0, split), repository, commit: raw.slice(at + 1) }
}

const jsonOutput = path.resolve(
  value('--json-output') ?? path.join(repoRoot, 'migration/generated/surface-matrix.json'),
)
const markdownOutput = path.resolve(
  value('--markdown-output') ?? path.join(repoRoot, 'migration/generated/surface-matrix.md'),
)
const fail = message => {
  console.error(`migration:${check ? 'check' : 'emit'} surface matrix: ${message}`)
  process.exit(1)
}

let matrix
try {
  matrix = buildSurfaceMatrix(
    await loadInventorySources({
      repoRoot,
      roots: values('--root').map(parseLabeledPath),
      snapshots: values('--snapshot').map(parseSnapshot),
    }),
  )
} catch (error) {
  fail(error instanceof Error ? error.message : String(error))
}

const mark = claim => (claim.applicable ? 'required' : '—')
const escape = input => String(input).replaceAll('|', '\\|').replaceAll('\n', ' ')
const lines = [
  '<!-- Generated by scripts/migration/emit-surface-matrix.mjs. Do not edit by hand. -->',
  '',
  '# Format × surface matrix',
  '',
  `Inventory projection: **${matrix.counts.rows}** format rows, **${matrix.counts.applicableClaims}** applicable surface claims. Generic smoke: **${matrix.counts.smokePassed} pass / ${matrix.counts.smokeMissing} missing**. Missing smoke remains visible here until P7 owner receipts exist; this generator does not manufacture evidence.`,
  '',
  '| Repository | Format | Codec contribution | ' + SURFACE_ANCHORS.join(' | ') + ' | Smoke |',
  '| --- | --- | --- | ' + SURFACE_ANCHORS.map(() => '---').join(' | ') + ' | --- |',
  ...matrix.rows.map(
    row =>
      `| ${escape(row.repository)} | \`${escape(row.format.id)}\` | \`${escape(row.contributionId)}\` | ${SURFACE_ANCHORS.map(anchor => mark(row.surfaces[anchor])).join(' | ')} | ❌ ${row.smoke.status} |`,
  ),
  '',
  '## Provenance',
  '',
  ...matrix.repositories.map(
    source =>
      `- **${escape(source.label)}** — ${escape(source.kind)}${source.commit === undefined ? '' : ` at \`${source.commit}\``}${source.path === undefined ? '' : `: \`${escape(source.path)}\``}`,
  ),
  '',
]
const [jsonPrettierOptions, markdownPrettierOptions] = await Promise.all([
  resolveConfig(jsonOutput),
  resolveConfig(markdownOutput),
])
const [json, markdown] = await Promise.all([
  format(JSON.stringify(matrix), { ...jsonPrettierOptions, parser: 'json' }),
  format(lines.join('\n'), { ...markdownPrettierOptions, parser: 'markdown' }),
])

if (check) {
  for (const [file, expected] of [
    [jsonOutput, json],
    [markdownOutput, markdown],
  ]) {
    if (!existsSync(file))
      fail(`${path.relative(repoRoot, file)} is missing; run pnpm migration:emit`)
    if (readFileSync(file, 'utf8') !== expected)
      fail(`${path.relative(repoRoot, file)} is stale; run pnpm migration:emit`)
  }
  if (!quiet) console.log(`migration:check surface matrix: ${matrix.counts.rows} rows up to date`)
} else {
  await Promise.all([
    mkdir(path.dirname(jsonOutput), { recursive: true }),
    mkdir(path.dirname(markdownOutput), { recursive: true }),
  ])
  writeFileSync(jsonOutput, json)
  writeFileSync(markdownOutput, markdown)
  if (!quiet) console.log(`migration:emit surface matrix: wrote ${matrix.counts.rows} format rows`)
}
