#!/usr/bin/env node
// Human-readable migration status and gap list (PLAN_MODKIT_MK3_FINAL_RU.md §3.5, блок 10 работа 7).
//
// Reads the generated inventory, the capability registry, the three release closures, the corpora
// readiness matrix, the product profiles and the projection matrix, and renders one page a person
// can read: what exists, what is proved, and exactly what is still missing inside each named
// release. Deterministic and timestamp-free — the freshness of the page is proved by regenerating
// it, the same way the inventory and the closures are.
//
// Usage: node scripts/migration/emit-status.mjs [--check] [--quiet]

import { readFileSync, writeFileSync } from 'node:fs'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'
import { parseCanonicalYaml } from './lib/canonical-yaml.mjs'
import { nearestOwedBlock } from './lib/nearest-block.mjs'

const repoRoot = path.resolve(fileURLToPath(new URL('../..', import.meta.url)))
const check = process.argv.includes('--check')
const quiet = process.argv.includes('--quiet')
const outputPath = path.join(repoRoot, 'migration/generated/status.md')

const readJson = file => JSON.parse(readFileSync(path.join(repoRoot, file), 'utf8'))
const readYaml = file => parseCanonicalYaml(readFileSync(path.join(repoRoot, file), 'utf8'))

const inventory = readJson('migration/generated/source-inventory.json')
const workflowLedger = readJson('migration/generated/vscode-workflow-ledger.json')
const registry = readYaml('migration/capabilities.yaml')
const projections = readYaml('migration/projections.yaml')
const lock = readJson('migration/oracle/legacy-oracle.lock.json')
const corpora = readJson('migration/corpora-readiness.json')
const profiles = readJson('migration/product-profiles.json')
const closures = {
  'mk3-ga': readJson('migration/priority-scope.mk3-ga.json'),
  'mk3-multiverse-ga': readJson('migration/priority-scope.mk3-multiverse-ga.json'),
  'mk3-deferred-games': readJson('migration/priority-scope.mk3-deferred-games.json'),
}

const compareUtf8 = (left, right) => Buffer.compare(Buffer.from(left), Buffer.from(right))
const UNRESOLVED = new Set(['missing', 'blocked', 'partial', 'unknown', 'deferred-post-ga'])
const CALLER_LABELS = new Map([
  ['automation', 'Automation'],
  ['cli', 'CLI'],
  ['electron', 'Electron'],
  ['pwa', 'PWA'],
  ['vscode', 'VS Code'],
])

const tally = (rows, pick) => {
  const counts = {}
  for (const row of rows) counts[pick(row)] = (counts[pick(row)] ?? 0) + 1
  return Object.entries(counts).sort(([left], [right]) => compareUtf8(left, right))
}
const table = (headers, rows) =>
  [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map(cells => `| ${cells.join(' | ')} |`),
  ].join('\n')

const lines = []
const push = (...text) => lines.push(...text, '')

push(
  '<!-- Generated by scripts/migration/emit-status.mjs (pnpm migration:report). Do not edit by hand. -->',
)
push('# Состояние переноса modkitx → Modkit MK3')
push(
  'Генерируемая сводка миграции. Страница намеренно без даты: свежесть доказывается повторной генерацией (`pnpm migration:check`), а не записанным временем. Источники — опечатанный oracle, слой 1 (`migration/generated/source-inventory.json`), workflow-ledger блока 14A, слой 2 (`migration/capabilities.yaml`) и три closure.',
)

push('## 1. Опечатанный oracle')
push(
  table(
    ['Показатель', 'Значение'],
    [
      ['legacy HEAD', `\`${lock.legacy.headCommit.slice(0, 12)}\``],
      ['index-записей', String(inventory.oracle.sealedIndexEntries)],
      ['удалено в worktree', String(inventory.oracle.sealedWorktreeDeletions)],
      ['tracked в опечатанном состоянии', String(inventory.oracle.sealedTrackedFiles)],
      ['sealed untracked', String(inventory.oracle.sealedUntrackedFiles)],
      ['всего файлов', String(inventory.oracle.sealedFiles)],
    ],
  ),
)

push('## 2. Слой 1 — source inventory')
push(
  `Всего единиц: **${inventory.counts.total}**. Контрольные числа сошлись: ${inventory.controlTotals.codecManifests} codec + ${inventory.controlTotals.gameManifests} game = ${inventory.controlTotals.manifestsTotal} manifests; VS Code ${inventory.controlTotals.vscodeCommands}/${inventory.controlTotals.vscodeCustomEditors}/${inventory.controlTotals.vscodeLanguages} commands/editors/languages.`,
)
push(
  table(
    ['Вид единицы', 'Единиц'],
    Object.entries(inventory.counts.byKind)
      .sort(([left], [right]) => compareUtf8(left, right))
      .map(([kind, count]) => [`\`${kind}\``, String(count)]),
  ),
)

push('### 2.1. Block 14A — VS Code + CLI workflow ledger')
push(
  `Ledger распределяет ровно **${workflowLedger.counts.legacyVsCode} VS Code + ${workflowLedger.counts.legacyCli} CLI = ${workflowLedger.counts.total}** legacy-единиц по трём честным корзинам: **${workflowLedger.counts.byDisposition['already-equivalent']}** уже заменены, **${workflowLedger.counts.byDisposition['release-candidate']}** входят в ${workflowLedger.counts.releaseCandidateGaps} точных задач Product GA, **${workflowLedger.counts.byDisposition['post-release']}** явно оставлены после релиза. Короткий список и полный backlog записаны в \`migration/generated/vscode-workflow-shortlist.json\` и \`migration/generated/vscode-workflow-backlog.json\`.`,
)
push(
  table(
    ['Поверхность', 'Legacy', 'X3 сейчас'],
    [
      [
        'commands',
        String(workflowLedger.surfaceComparison.legacyVsCode.commands),
        String(workflowLedger.surfaceComparison.currentX3VsCode.commands),
      ],
      [
        'custom editors',
        String(workflowLedger.surfaceComparison.legacyVsCode.customEditors),
        String(workflowLedger.surfaceComparison.currentX3VsCode.customEditors),
      ],
      [
        'languages',
        String(workflowLedger.surfaceComparison.legacyVsCode.languages),
        String(workflowLedger.surfaceComparison.currentX3VsCode.languages),
      ],
      [
        'views',
        String(workflowLedger.surfaceComparison.legacyVsCode.views),
        String(workflowLedger.surfaceComparison.currentX3VsCode.views),
      ],
    ],
  ),
)
const sharedCommandCallers =
  workflowLedger.sharedCommandTargets.length === 0
    ? []
    : [...new Set(workflowLedger.sharedCommandTargets[0].hostCallers ?? [])]
        .filter(caller =>
          workflowLedger.sharedCommandTargets.every(row => row.hostCallers?.includes(caller)),
        )
        .sort(compareUtf8)
push(
  `Shared subject commands: ${workflowLedger.sharedCommandTargets
    .map(row => `\`${row.commandId}\``)
    .join(', ')}. Доказанные callers: ${
    sharedCommandCallers.map(caller => CALLER_LABELS.get(caller) ?? `\`${caller}\``).join(', ') ||
    'нет общих callers'
  }.`,
)

const capabilities = registry.capabilities
push('## 3. Слой 2 — semantic capability registry')
push(
  `Строк-возможностей: **${capabilities.length}**. Owner additions заморожены ${registry.ownerAdditionsFrozenOn}.`,
)
push('### 3.1. Release track и обязательность')
push(
  table(
    ['releaseTrack', 'Строк', 'obligation', 'Строк'],
    (() => {
      const tracks = tally(capabilities, row => row.releaseTrack)
      const obligations = tally(capabilities, row => row.obligation)
      const height = Math.max(tracks.length, obligations.length)
      return Array.from({ length: height }, (_, index) => [
        tracks[index] ? `\`${tracks[index][0]}\`` : '',
        tracks[index] ? String(tracks[index][1]) : '',
        obligations[index] ? `\`${obligations[index][0]}\`` : '',
        obligations[index] ? String(obligations[index][1]) : '',
      ])
    })(),
  ),
)
push('### 3.2. Три независимые оси')
push(
  'Покрытие не доказывает реализацию, реализация не доказывает evidence — это разные поля и разные числа.',
)
push(
  table(
    ['allocation', 'Строк', 'migrationState', 'Строк', 'evidenceLevel', 'Строк'],
    (() => {
      const allocation = tally(capabilities, row => row.allocation.state)
      const migration = tally(capabilities, row => row.migrationState)
      const evidence = tally(capabilities, row => row.evidenceLevel)
      const height = Math.max(allocation.length, migration.length, evidence.length)
      return Array.from({ length: height }, (_, index) => [
        allocation[index] ? `\`${allocation[index][0]}\`` : '',
        allocation[index] ? String(allocation[index][1]) : '',
        migration[index] ? `\`${migration[index][0]}\`` : '',
        migration[index] ? String(migration[index][1]) : '',
        evidence[index] ? evidence[index][0] : '',
        evidence[index] ? String(evidence[index][1]) : '',
      ])
    })(),
  ),
)
push('### 3.3. Доказанные writers')
const writers = capabilities.filter(row => row.writerEvidence.startsWith('write-reopen-compared'))
push(
  writers.length === 0
    ? 'Ни один writer не доказан.'
    : table(
        ['Возможность', 'writerEvidence', 'Тест'],
        writers.map(row => [
          `\`${row.capabilityId}\``,
          `\`${row.writerEvidence}\``,
          row.closedBy.tests.map(test => `\`${test}\``).join('<br>'),
        ]),
      ),
)

push('## 4. Именованные closure')
push(
  'Исполняемый порядок: `mk3-ga` → `mk3-multiverse-ga` → STOP. `mk3-deferred-games` неактивен до нового прямого указания владельца; это новое имя исторического `mk3-pre-multiverse`, который больше не является gate Multiverse.',
)
push(
  table(
    ['Release', 'Всего', 'Seed', 'Транзитивных', 'Нерешённых', 'Ближайший блок'],
    Object.entries(closures).map(([name, scope]) => [
      `\`${name}\``,
      String(scope.counts.total),
      String(scope.counts.seed),
      String(scope.counts.transitiveDependencies),
      String(scope.units.filter(unit => UNRESOLVED.has(unit.migrationState)).length),
      // The earliest block that still owes something — not merely the first key. See
      // `lib/nearest-block.mjs` for the two ways the old one-liner lied.
      nearestOwedBlock(scope.deadlines, id =>
        UNRESOLVED.has(scope.units.find(unit => unit.capabilityId === id)?.migrationState),
      ) ?? '—',
    ]),
  ),
)
push('### 4.1. Дедлайны `mk3-ga` по planned block')
push(
  table(
    ['Planned block', 'Units', 'Из них нерешённых'],
    Object.entries(closures['mk3-ga'].deadlines)
      .sort(([left], [right]) => Number(left.slice(6)) - Number(right.slice(6)))
      .map(([block, ids]) => [
        `\`${block}\``,
        String(ids.length),
        String(
          ids.filter(id =>
            UNRESOLVED.has(
              closures['mk3-ga'].units.find(unit => unit.capabilityId === id).migrationState,
            ),
          ).length,
        ),
      ]),
  ),
)

push('## 5. Gap list — что осталось в `mk3-ga`')
const gaps = closures['mk3-ga'].units
  .filter(unit => UNRESOLVED.has(unit.migrationState))
  .sort(
    (left, right) =>
      left.plannedBlock - right.plannedBlock || compareUtf8(left.capabilityId, right.capabilityId),
  )
push(
  `Строк с нерешённым состоянием: **${gaps.length}** из ${closures['mk3-ga'].counts.total}. Список отсортирован по planned block: строка становится просроченной для \`pnpm priority:check --phase block-N\`, как только её блок пройден.`,
)
for (const block of [...new Set(gaps.map(unit => unit.plannedBlock))].sort((a, b) => a - b)) {
  const blockGaps = gaps.filter(unit => unit.plannedBlock === block)
  push(`### Блок ${block} — ${blockGaps.length} строк`)
  push(
    table(
      ['Возможность', 'migrationState', 'evidence', 'Владелец'],
      blockGaps.map(unit => [
        `\`${unit.capabilityId}\``,
        `\`${unit.migrationState}\``,
        unit.evidenceLevel,
        `\`${unit.owner}\``,
      ]),
    ),
  )
}

push('## 6. Дополнительные gaps следующих release')
const closureEntries = Object.entries(closures)
for (let index = 1; index < closureEntries.length; index += 1) {
  const [name, scope] = closureEntries[index]
  const [predecessorName, predecessor] = closureEntries[index - 1]
  const predecessorIds = new Set(predecessor.units.map(unit => unit.capabilityId))
  const incrementalGaps = scope.units
    .filter(unit => !predecessorIds.has(unit.capabilityId) && UNRESOLVED.has(unit.migrationState))
    .sort(
      (left, right) =>
        left.plannedBlock - right.plannedBlock ||
        compareUtf8(left.capabilityId, right.capabilityId),
    )
  push(`### \`${name}\` сверх \`${predecessorName}\` — ${incrementalGaps.length} строк`)
  push(
    incrementalGaps.length === 0
      ? 'Новых нерешённых строк нет.'
      : table(
          ['Возможность', 'migrationState', 'evidence', 'Владелец'],
          incrementalGaps.map(unit => [
            `\`${unit.capabilityId}\``,
            `\`${unit.migrationState}\``,
            unit.evidenceLevel,
            `\`${unit.owner}\``,
          ]),
        ),
  )
}

push('## 7. Готовность корпусов')
push(
  table(
    ['Корпус', 'Release track', 'Вертикаль', 'Статус', 'Переменные', 'Действие владельца'],
    corpora.corpora.map(entry => [
      entry.displayName,
      `\`${entry.releaseTrack}\``,
      `блок ${entry.verticalBlock}`,
      `\`${entry.status}\``,
      entry.environmentVariables.map(variable => `\`${variable}\``).join(', '),
      entry.ownerAction === null ? '—' : entry.ownerAction,
    ]),
  ),
)

push('## 8. Профили продукта')
push(
  table(
    ['Preset', 'Входит с release', 'Статус', 'Семейств', 'Планируемых', 'Минимальный closure'],
    profiles.presets.map(preset => [
      preset.displayName,
      `\`${preset.introducedInClosure}\``,
      `\`${preset.status}\``,
      String(preset.extensionFamilies.length),
      String(preset.plannedFamilies.length),
      preset.minimalClosure ? 'да' : 'нет',
    ]),
  ),
)

push('## 9. Матрица проекций')
push(
  table(
    ['Plane', 'Что делать', 'portableProfile', 'Зрелость артефакта'],
    projections.planes.map(plane => [
      `\`${plane.plane}\``,
      `\`${plane.action}\``,
      `\`${plane.portableProfile}\``,
      `\`${plane.artifactMaturity}\``,
    ]),
  ),
)

push('## 10. Неотображённый остаток инвентаря')
push(
  `Единиц, сопоставленных capability registry или workflow-ledger: **${registry.counts.mappedUnits}**; явно неотображённых: **${registry.counts.unmappedUnits}**. Сумма равна ${registry.counts.inventoryUnits} — ни одна единица не потеряна.`,
)
push(
  table(
    ['Вид единицы', 'Единиц', 'План'],
    registry.unmapped
      .slice()
      .sort((left, right) => compareUtf8(left.selector, right.selector))
      .map(rule => [`\`${rule.selector}\``, String(rule.count), rule.plan]),
  ),
)

const prettierOptions = await resolveConfig(outputPath)
const rendered = await format(lines.join('\n'), { ...prettierOptions, parser: 'markdown' })

if (check) {
  let existing = ''
  try {
    existing = readFileSync(outputPath, 'utf8')
  } catch {
    console.error(
      'migration:report --check: migration/generated/status.md is missing; run pnpm migration:report',
    )
    process.exit(1)
  }
  if (existing !== rendered) {
    console.error(
      'migration:report --check: migration/generated/status.md is stale; run pnpm migration:report',
    )
    process.exit(1)
  }
  if (!quiet)
    console.log(`migration:report --check: status.md up to date (${gaps.length} open mk3-ga gaps)`)
} else {
  await mkdir(path.dirname(outputPath), { recursive: true })
  writeFileSync(outputPath, rendered, 'utf8')
  if (!quiet)
    console.log(
      `migration:report: wrote migration/generated/status.md (${gaps.length} open mk3-ga gaps)`,
    )
}
