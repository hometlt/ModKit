#!/usr/bin/env node
// GA recovery wave 2C §3 (F12): the parity matrix used to be a hand-written document
// (references/modkit-docs/MK3/reports/MK3_COMPONENT_TEST_MATRIX_2026-08-31.md) — a measurement that
// could drift from the registry with nobody noticing. That hand-written matrix carried a tester's
// prose (Scenario/Input/Expected/Actual, evidence references like "E29") that no generator reading
// only capabilities.yaml and the ledger can honestly reproduce, so this is not a byte-for-byte
// replacement of its content. It is a new, purely mechanical view over the two machine-checked
// sources this repository already trusts: the layer-2 capability registry (migration/capabilities.yaml)
// and the Block 14A VS Code + CLI workflow ledger (migration/generated/vscode-workflow-ledger.json).
// Every field below is copied, not synthesized — nothing here is prose a human remembered.
//
// Usage: node scripts/migration/emit-parity-matrix.mjs [--check] [--quiet]
//   [--registry <path>] [--ledger <path>] [--output <path>]

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'
import { parseCanonicalYaml } from './lib/canonical-yaml.mjs'

const repoRoot = path.resolve(fileURLToPath(new URL('../..', import.meta.url)))
const args = process.argv.slice(2)
const argValue = flag => {
  const index = args.indexOf(flag)
  return index === -1 ? undefined : args[index + 1]
}
const check = args.includes('--check')
const quiet = args.includes('--quiet')
const registryPath = path.resolve(
  argValue('--registry') ?? path.join(repoRoot, 'migration/capabilities.yaml'),
)
const ledgerPath = path.resolve(
  argValue('--ledger') ?? path.join(repoRoot, 'migration/generated/vscode-workflow-ledger.json'),
)
const outputPath = path.resolve(
  argValue('--output') ?? path.join(repoRoot, 'migration/generated/parity-matrix.md'),
)

const fail = message => {
  console.error(`migration:${check ? 'check' : 'emit'} parity matrix: ${message}`)
  process.exit(1)
}

for (const [label, file] of [
  ['registry', registryPath],
  ['ledger', ledgerPath],
]) {
  if (!existsSync(file)) fail(`missing ${label} input ${path.relative(repoRoot, file)}`)
}

const compareUtf8 = (left, right) => Buffer.compare(Buffer.from(left), Buffer.from(right))
const sorted = (values, pick = value => value) =>
  [...values].sort((left, right) => compareUtf8(pick(left), pick(right)))
const table = (headers, rows) =>
  [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map(cells => `| ${cells.join(' | ')} |`),
  ].join('\n')
// Table cells are single-line: escape any literal pipe so a stray one can never break a row, and
// cap length so one long knownLoss entry can't blow out the table's readability.
const cell = (value, maxLength = 140) => {
  const escaped = String(value).replaceAll('|', '\\|').replaceAll('\n', ' ')
  return escaped.length > maxLength ? `${escaped.slice(0, maxLength - 1)}…` : escaped
}
const code = value => `\`${value}\``

const registry = parseCanonicalYaml(readFileSync(registryPath, 'utf8'))
const ledger = JSON.parse(readFileSync(ledgerPath, 'utf8'))

if (registry.schemaVersion !== 'capability-registry-1') {
  fail(`unsupported registry schema ${String(registry.schemaVersion)}`)
}
if (!Array.isArray(registry.capabilities)) fail('registry.capabilities must be an array')
if (ledger.schemaVersion !== 'vscode-workflow-ledger-2') {
  fail(`unsupported ledger schema ${String(ledger.schemaVersion)}`)
}

// capabilityId is `<family>/<...>`; the family segment (format, game, platform, vertical, uv,
// addition, block9, experimental, proof) is the only grouping this registry already carries in the
// identifier itself, so grouping by it needs no new taxonomy invented for this report.
const familyOf = row => row.capabilityId.split('/')[0]
const families = sorted(new Set(registry.capabilities.map(familyOf)))

const lines = []
const push = (...text) => lines.push(...text, '')

push(
  '<!-- Generated by scripts/migration/emit-parity-matrix.mjs (pnpm migration:report). Do not edit by hand. -->',
)
push('# Сгенерированная parity-матрица')
push(
  'Механическая проекция `migration/capabilities.yaml` (реестр возможностей) и ' +
    '`migration/generated/vscode-workflow-ledger.json` (Block 14A workflow ledger). Каждое поле ' +
    'скопировано из одного из этих двух источников — здесь нет ни одной строки, которую кто-то ' +
    'вспомнил или сформулировал заново. Расхождение с закоммиченной копией ловит ' +
    '`scripts/test/parity-matrix.test.ts`.',
)
push(
  'Историческая ручная матрица тестировщика (Scenario/Input/Expected/Actual, evidence-ссылки E01–E33) ' +
    'несёт наблюдения, которые этот генератор не может честно воспроизвести — она перемещена в ' +
    '`references/modkit-docs/MK3/archive/MK3_COMPONENT_TEST_MATRIX_2026-08-31.md` (docs repo) и ' +
    'сохраняет историческую ценность, но не является текущим измерением.',
)

push('## 1. Workflow ledger — три честные корзины')
push(
  `Ledger распределяет **${ledger.counts.total}** legacy-единиц (VS Code ${ledger.counts.legacyVsCode} + CLI ${ledger.counts.legacyCli}) по трём дизъюнктным корзинам disposition. Источник: \`migration/generated/vscode-workflow-ledger.json\`.`,
)
const dispositionOrder = ['already-equivalent', 'release-candidate', 'post-release']
push(
  table(
    ['Корзина (disposition)', 'Фактов'],
    dispositionOrder.map(disposition => [
      code(disposition),
      String(ledger.counts.byDisposition[disposition] ?? 0),
    ]),
  ),
)
push(
  `Product GA gaps: **${ledger.counts.releaseCandidateGaps}**. Наблюдаемых текущих X3-фактов: **${ledger.counts.currentX3ObservedFacts}**.`,
)

push('### 1.1. Workflow-строки')
push(
  table(
    ['workflowId', 'plannedSlice', 'disposition', 'legacy-единиц'],
    sorted(ledger.workflows, row => row.workflowId).map(row => [
      code(row.workflowId),
      code(row.plannedSlice),
      code(row.classification.disposition),
      String(row.legacyUnitCount),
    ]),
  ),
)

push('## 2. Capability registry по family / releaseTrack')
push(
  `Строк-возможностей в реестре: **${registry.capabilities.length}**. Источник: \`migration/capabilities.yaml\`. Столбец knownLoss показывает число записей и первую строку (обрезанную) — не полный текст.`,
)
for (const family of families) {
  const familyRows = registry.capabilities.filter(row => familyOf(row) === family)
  push(`### 2.${families.indexOf(family) + 1}. \`${family}\` (${familyRows.length})`)
  const tracks = sorted(new Set(familyRows.map(row => row.releaseTrack)))
  for (const track of tracks) {
    const rows = sorted(
      familyRows.filter(row => row.releaseTrack === track),
      row => row.capabilityId,
    )
    push(`#### \`${family}\` / \`${track}\` (${rows.length})`)
    push(
      table(
        [
          'capabilityId',
          'evidenceLevel',
          'hostEvidence',
          'obligation',
          'allocation.state',
          'knownLoss',
        ],
        rows.map(row => [
          code(row.capabilityId),
          row.evidenceLevel,
          code(row.hostEvidence),
          code(row.obligation),
          code(row.allocation.state),
          row.knownLoss.length === 0 ? '—' : `${row.knownLoss.length}: ${cell(row.knownLoss[0])}`,
        ]),
      ),
    )
  }
}

const prettierOptions = await resolveConfig(outputPath)
const rendered = await format(lines.join('\n'), { ...prettierOptions, parser: 'markdown' })

if (check) {
  let existing = ''
  try {
    existing = readFileSync(outputPath, 'utf8')
  } catch {
    fail(`${path.relative(repoRoot, outputPath)} is missing; run pnpm migration:emit`)
  }
  if (existing !== rendered) {
    fail(`${path.relative(repoRoot, outputPath)} is stale; run pnpm migration:emit`)
  }
  if (!quiet) {
    console.log(
      `migration:check parity matrix: ${registry.capabilities.length} capability rows across ${families.length} families, ${ledger.counts.total} ledger facts up to date`,
    )
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true })
  writeFileSync(outputPath, rendered)
  if (!quiet) {
    console.log(
      `migration:emit parity matrix: wrote ${registry.capabilities.length} capability rows across ${families.length} families, ${ledger.counts.total} ledger facts`,
    )
  }
}
