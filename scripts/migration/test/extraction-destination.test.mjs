import assert from 'node:assert/strict'
import { test } from 'node:test'
import { mkdtemp, readFile, rm, writeFile, access } from 'node:fs/promises'
import { spawnSync } from 'node:child_process'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(fileURLToPath(new URL('../../..', import.meta.url)))
const extractor = path.join(root, 'scripts/migration/extract-pinned-symbols.mjs')
const existing = path.join(root, 'packages/codec-kit/crypto-digest-kernels.config.json')
const run = (config, destination, check = false) =>
  spawnSync(
    process.execPath,
    [
      extractor,
      '--config',
      config,
      '--destination-root',
      destination,
      ...(check ? ['--check'] : []),
    ],
    { cwd: root, encoding: 'utf8' },
  )

test('explicit core destination preserves existing generated bytes and provenance', () => {
  const result = run(existing, root, true)
  assert.equal(result.status, 0, result.stderr || result.stdout)
})

test('a separate declared package uses the same exact extraction and drift check', async () => {
  const directory = await mkdtemp(path.join(tmpdir(), 'mk3-extraction-'))
  try {
    await writeFile(
      path.join(directory, 'package.json'),
      '{"name":"extraction-fixture","private":true}',
    )
    const config = JSON.parse(await readFile(existing, 'utf8'))
    config.output = 'src/kernel.ts'
    config.provenance = 'KERNEL-PROVENANCE.json'
    const configPath = path.join(directory, 'kernel-config.json')
    await writeFile(configPath, JSON.stringify(config))
    const result = run(configPath, directory)
    assert.equal(result.status, 0, result.stderr || result.stdout)
    const checked = run(configPath, directory, true)
    assert.equal(checked.status, 0, checked.stderr || checked.stdout)
    const originalReceipt = JSON.parse(
      await readFile(path.join(root, 'packages/codec-kit/MK2-DIGEST-KERNELS.json'), 'utf8'),
    )
    const emittedReceipt = JSON.parse(
      await readFile(path.join(directory, config.provenance), 'utf8'),
    )
    assert.deepEqual(emittedReceipt.sources, originalReceipt.sources)
    assert.equal(emittedReceipt.commit, originalReceipt.commit)
    assert.match(
      await readFile(path.join(directory, config.output), 'utf8'),
      /Source selection: kernel-config\.json/,
    )
    await writeFile(path.join(directory, config.output), '// drift\n')
    const changed = run(configPath, directory, true)
    assert.notEqual(changed.status, 0)
    assert.match(changed.stderr, /pinned extraction differs/)
  } finally {
    assert.equal(path.dirname(path.resolve(directory)), path.resolve(tmpdir()))
    await rm(directory, { recursive: true, force: true })
  }
})

test('both output destinations are confined before the first write', async () => {
  const directory = await mkdtemp(path.join(tmpdir(), 'mk3-extraction-'))
  try {
    await writeFile(
      path.join(directory, 'package.json'),
      '{"name":"extraction-fixture","private":true}',
    )
    const config = JSON.parse(await readFile(existing, 'utf8'))
    config.output = 'src/kernel.ts'
    config.provenance = '../must-not-write.json'
    const configPath = path.join(directory, 'kernel-config.json')
    await writeFile(configPath, JSON.stringify(config))
    const result = run(configPath, directory)
    assert.notEqual(result.status, 0)
    assert.match(result.stderr, /target must remain inside the destination repository/)
    await assert.rejects(access(path.join(directory, config.output)), { code: 'ENOENT' })
  } finally {
    assert.equal(path.dirname(path.resolve(directory)), path.resolve(tmpdir()))
    await rm(directory, { recursive: true, force: true })
  }
})
