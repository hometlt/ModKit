#!/usr/bin/env node
// Emits the published .json schema artifacts from the schema consts in core and
// sdk (single wire authority; DoR workflow step 2). Serialization is
// canonical (sorted keys, LF, trailing newline) so the artifacts are byte-stable.
// `--check` compares instead of writing and exits 1 on drift. Requires a built sdk.

import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import process from 'node:process'
import { canonicalJsonStringify, sourceSpanSchema } from '../packages/core/dist/index.js'
import * as sdk from '../packages/sdk/dist/index.js'

const root = fileURLToPath(new URL('..', import.meta.url))
const check = process.argv.includes('--check')
const sdkRequire = createRequire(join(root, 'packages', 'sdk', 'package.json'))
const Ajv2020 = sdkRequire('ajv/dist/2020.js').default
const standaloneCode = sdkRequire('ajv/dist/standalone/index.js').default

const artifacts = new Map([
  [join(root, 'packages', 'core', 'schemas', 'source-span.v1.schema.json'), sourceSpanSchema],
  [
    join(root, 'packages', 'sdk', 'schemas', 'extension-manifest.v1.schema.json'),
    sdk.extensionManifestSchema,
  ],
  [
    join(root, 'packages', 'sdk', 'schemas', 'extension-manifest-modkit-block.v1.schema.json'),
    sdk.modkitBlockSchema,
  ],
  [
    join(root, 'packages', 'sdk', 'schemas', 'extension-requirement.v1.schema.json'),
    sdk.extensionRequirementSchema,
  ],
  [
    join(root, 'packages', 'sdk', 'schemas', 'codec-contribution-spec.v1.schema.json'),
    sdk.codecContributionSpecV1Schema,
  ],
  [
    join(root, 'packages', 'sdk', 'schemas', 'service-provider-contribution-spec.v1.schema.json'),
    sdk.serviceProviderContributionSpecV1Schema,
  ],
  [
    join(root, 'packages', 'sdk', 'schemas', 'viewer-contribution-spec.v1.schema.json'),
    sdk.viewerContributionSpecV1Schema,
  ],
  [
    join(root, 'packages', 'sdk', 'schemas', 'editor-contribution-spec.v1.schema.json'),
    sdk.editorContributionSpecV1Schema,
  ],
  [
    join(root, 'packages', 'sdk', 'schemas', 'trait-definition-spec.v1.schema.json'),
    sdk.traitDefinitionSpecV1Schema,
  ],
  [
    join(root, 'packages', 'sdk', 'schemas', 'contract-definition-spec.v1.schema.json'),
    sdk.contractDefinitionSpecV1Schema,
  ],
  [
    join(root, 'packages', 'sdk', 'schemas', 'subject-descriptor.v2.schema.json'),
    sdk.subjectDescriptorV2Schema,
  ],
])
if (sdk.contributionManifestSchema !== undefined) {
  artifacts.set(
    join(root, 'packages', 'sdk', 'schemas', 'contribution-manifest.v1.schema.json'),
    sdk.contributionManifestSchema,
  )
  artifacts.set(
    join(root, 'packages', 'sdk', 'schemas', 'runtime-variant-declaration.v1.schema.json'),
    sdk.runtimeVariantDeclarationSchema,
  )
  artifacts.set(
    join(root, 'packages', 'sdk', 'schemas', 'scoped-contract-requirement.v1.schema.json'),
    sdk.scopedContractRequirementSchema,
  )
}

function validatorExportName(path) {
  const relativePath = relative(root, path).replaceAll('\\', '/')
  const basename = relativePath.slice(relativePath.lastIndexOf('/') + 1).replace('.schema.json', '')
  const words = basename.split(/[^A-Za-z0-9]+/u).filter(Boolean)
  return words
    .map((word, index) =>
      index === 0
        ? `${word[0]?.toLowerCase() ?? ''}${word.slice(1)}`
        : `${word[0]?.toUpperCase() ?? ''}${word.slice(1)}`,
    )
    .join('')
}

function renderStandaloneValidators() {
  const generated = new Map()
  const rows = []
  const validators = [
    ...[...artifacts].map(([path, schema]) => ({ name: validatorExportName(path), schema })),
    {
      name: 'dataSourceContractDefinitionV1',
      schema: sdk.dataSourceContractDefinitionSpecV1Schema,
    },
  ]
  for (const { name, schema } of validators) {
    const ajv = new Ajv2020({
      allErrors: true,
      strict: true,
      addUsedSchema: false,
      code: { source: true, esm: true, lines: true },
    })
    const key = `modkitx-precompiled:${name}`
    ajv.addSchema(schema, key)
    const compiled = standaloneCode(ajv, { [name]: key }).replace(
      /const ([A-Za-z_$][A-Za-z0-9_$]*) = require\("([^"]+)"\)\.default;/gu,
      (_match, binding, specifier) => {
        const moduleSpecifier = specifier.endsWith('.js') ? specifier : `${specifier}.js`
        return `import * as ${binding}Module from "${moduleSpecifier}";
const ${binding} = ${binding}Module.default?.default ?? ${binding}Module.default;`
      },
    ).trimEnd()
    generated.set(
      join(validatorDirectory, `${name}.ts`),
      `// @ts-nocheck
/* eslint-disable */
// Generated by scripts/emit-schemas.mjs. Do not edit by hand.
${compiled}
`,
    )
    rows.push([canonicalJsonStringify(schema), name])
  }
  const imports = rows
    .map(([, name]) => `import { ${name} } from './validators.generated/${name}.js'`)
    .join('\n')
  const registry = rows
    .map(([fingerprint, name]) => `  [${JSON.stringify(fingerprint)}, ${name}],`)
    .join('\n')
  generated.set(
    validatorArtifact,
    `// @ts-nocheck
/* eslint-disable */
// Generated by scripts/emit-schemas.mjs. Do not edit by hand.
// AJV compilation happens only in the build tool; this module is CSP-safe runtime code.
${imports}

export const PRECOMPILED_SCHEMA_VALIDATORS: ReadonlyMap<
  string,
  (value: unknown) => unknown
> = new Map([
${registry}
])
`,
  )
  return generated
}

const validatorDirectory = join(root, 'packages', 'sdk', 'src', 'manifest', 'validators.generated')
const validatorArtifact = join(
  root,
  'packages',
  'sdk',
  'src',
  'manifest',
  'validators.generated.ts',
)
const renderedValidators = renderStandaloneValidators()

const stale = []
for (const [path, schema] of artifacts) {
  const rendered = canonicalJsonStringify(schema)
  if (check) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined
    if (current !== rendered) stale.push(relative(root, path).replaceAll('\\', '/'))
  } else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, rendered, 'utf8')
  }
}
for (const [path, rendered] of renderedValidators) {
  if (check) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined
    if (current !== rendered) stale.push(relative(root, path).replaceAll('\\', '/'))
  } else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, rendered, 'utf8')
  }
}
if (check && existsSync(validatorDirectory)) {
  for (const name of readdirSync(validatorDirectory)) {
    const path = join(validatorDirectory, name)
    if (name.endsWith('.ts') && !renderedValidators.has(path)) {
      stale.push(`${relative(root, path).replaceAll('\\', '/')} (unexpected)`)
    }
  }
}

if (check) {
  const managedDirectories = [
    join(root, 'packages', 'core', 'schemas'),
    join(root, 'packages', 'sdk', 'schemas'),
  ]
  for (const directory of managedDirectories) {
    if (!existsSync(directory)) continue
    for (const name of readdirSync(directory)) {
      if (!name.endsWith('.schema.json')) continue
      const path = join(directory, name)
      if (!artifacts.has(path)) {
        stale.push(`${relative(root, path).replaceAll('\\', '/')} (unexpected)`)
      }
    }
  }
}

if (check && stale.length > 0) {
  console.error(`schemas out of date (run: pnpm schemas:emit): ${stale.join(', ')}`)
  process.exit(1)
}
console.log(
  check
    ? `schemas and standalone validators up to date (${artifacts.size})`
    : `emitted ${artifacts.size} schema artifact(s) and standalone validator registry`,
)
