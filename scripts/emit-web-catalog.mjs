#!/usr/bin/env node
/**
 * Web/PWA extension catalog (S6): the browser has no filesystem to inventory, so the build attests
 * the bundled extensions once and the page composes from the attestation. For every bundled codec
 * extension whose runtime dependencies are covered by the worker vendor bundles, this script
 * runs the *same* loader the Node hosts use
 * (`loadExtensionDirectory` from the built host) and serializes its `ExtensionInput` — files,
 * pre-read contribution documents and their digests, the artifact digest and the per-file
 * digests — into `apps/web/generated/extension-catalog.js`, with the artifact root as a path
 * relative to the app origin (`extensions/<name>/`).
 *
 * Honesty: the catalog's `artifactDigest` is a build-time attestation of the served bytes; the
 * page's gate check compares against it, and the browser worker backend re-verifies every file's
 * bytes against `fileDigests` at load (verify-then-snapshot). Extensions with other npm
 * dependencies are listed under `excluded` with the reason, never silently dropped.
 *
 * Runs after `pnpm bundle` (imports the built host); byte-stable; `--check` for the gate.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { format } from 'prettier'
import { authoredExtensionRootsRelativeTo } from './lib/authored-extension-roots.mjs'

const scriptPath = fileURLToPath(import.meta.url)
const defaultRoot = resolve(dirname(scriptPath), '..')
const OUTPUT_NAME = 'extension-catalog.js'
const TYPES_NAME = 'extension-catalog.d.ts'
const TYPES_SOURCE = `// Generated by scripts/emit-web-catalog.mjs. Do not edit by hand.
import type { WebExtensionCatalog } from '../src/subjects.js'

export declare const WEB_EXTENSION_CATALOG: WebExtensionCatalog
`
/** Bare specifiers the web worker vendor bundles cover (apps/web/scripts/build.mjs). */
export const WEB_WORKER_VENDORED = Object.freeze([
  '@modkitx-x3/codec-kit',
  '@modkitx-x3/core',
  '@modkitx-x3/sdk',
  '@rgrove/parse-xml',
  'smol-toml',
  'yaml',
])

function json(path) {
  return JSON.parse(readFileSync(path, 'utf8'))
}

function sortedJson(value) {
  return JSON.stringify(sortKeys(value), null, 2)
}

function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys)
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map(key => [key, sortKeys(value[key])]),
    )
  }
  return value
}

/** Product codec extensions, split into vendored (catalogued) and excluded. */
export function selectWebExtensions(root) {
  const extensionsRoot = join(root, 'extensions')
  const roots = authoredExtensionRootsRelativeTo(join(extensionsRoot, 'common')).map(entry => ({
    ...entry,
    relativePath: `common/${entry.relativePath}`,
  }))
  const ps1Root = join(extensionsRoot, 'ps1')
  if (existsSync(join(ps1Root, 'package.json'))) {
    roots.push({ directory: ps1Root, relativePath: 'ps1' })
  }
  const included = []
  const excluded = []
  for (const { directory: dir, relativePath } of roots) {
    const packagePath = join(dir, 'package.json')
    if (!existsSync(packagePath)) continue
    const pkg = json(packagePath)
    const patterns = pkg.modkit?.contributionManifests
    if (!Array.isArray(patterns)) continue
    const contributionsDir = join(dir, 'contributions')
    const hasCodec =
      existsSync(contributionsDir) &&
      readdirSync(contributionsDir)
        .filter(file => file.endsWith('.json'))
        .some(file => {
          const manifest = json(join(contributionsDir, file))
          return (
            manifest.contract?.id === 'org.modkitx/codec-contribution' &&
            manifest.contract?.major === 1
          )
        })
    if (!hasCodec) continue
    const dependencies = Object.keys(pkg.dependencies ?? {}).sort()
    const missing = dependencies.filter(dep => !WEB_WORKER_VENDORED.includes(dep))
    const name = pkg.modkit.id
    if (missing.length > 0) {
      excluded.push({
        name,
        reason: `runtime dependencies not vendored for the worker: ${missing.join(', ')}`,
      })
      continue
    }
    included.push({ directory: dir, name, relativePath })
  }
  return {
    included: included.sort((left, right) =>
      left.relativePath < right.relativePath ? -1 : left.relativePath > right.relativePath ? 1 : 0,
    ),
    excluded: excluded.sort((left, right) =>
      left.name < right.name ? -1 : left.name > right.name ? 1 : 0,
    ),
  }
}

async function buildCatalog(root) {
  const { loadExtensionDirectory } = await import(
    pathToFileURL(join(root, 'packages', 'host', 'dist', 'node', 'index.js')).href
  )
  const { included, excluded } = selectWebExtensions(root)
  const extensions = []
  for (const extension of included) {
    const { directory, name, relativePath } = extension
    const input = await loadExtensionDirectory(directory)
    extensions.push({
      name,
      source: `extensions/${relativePath}`,
      artifactRoot: `extensions/${name}/`,
      containers: input.containers,
      files: input.files,
      documents: [...input.documents.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
      documentDigests: [...input.documentDigests.entries()].sort(([a], [b]) =>
        a < b ? -1 : a > b ? 1 : 0,
      ),
      artifact: {
        inventoryRecordId: input.artifact.inventoryRecordId,
        artifactDigest: input.artifact.artifactDigest,
        fileDigests: input.artifact.fileDigests ?? {},
      },
    })
  }
  const body = sortedJson({ schemaVersion: 1, extensions, excluded })
  const source =
    `// Generated by scripts/emit-web-catalog.mjs. Do not edit by hand.\n` +
    `// Build-time attestation of the bundled extensions the PWA serves under \`extensions/<name>/\`;\n` +
    `// the browser worker backend re-verifies every file's bytes against \`fileDigests\` at load.\n` +
    `export const WEB_EXTENSION_CATALOG = Object.freeze(${body})\n`
  return format(source, { parser: 'babel', singleQuote: true, semi: false, printWidth: 100 })
}

export async function emitWebCatalog({ root = defaultRoot, check = false } = {}) {
  const output = join(resolve(root), 'apps', 'web', 'generated')
  const expected = await buildCatalog(root)
  const path = join(output, OUTPUT_NAME)
  const typesPath = join(output, TYPES_NAME)
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== expected) {
      throw new Error(`web extension catalog is stale: apps/web/generated/${OUTPUT_NAME}`)
    }
    if (!existsSync(typesPath) || readFileSync(typesPath, 'utf8') !== TYPES_SOURCE) {
      throw new Error(`web extension catalog types are stale: apps/web/generated/${TYPES_NAME}`)
    }
    return { state: 'checked' }
  }
  mkdirSync(output, { recursive: true })
  writeFileSync(path, expected, 'utf8')
  writeFileSync(typesPath, TYPES_SOURCE, 'utf8')
  return { state: 'emitted' }
}

function parseArguments(argv) {
  let root = defaultRoot
  let check = false
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--check') check = true
    else if (argument === '--root') {
      const value = argv[index + 1]
      if (value === undefined) throw new Error('--root requires a path')
      root = resolve(value)
      index += 1
    } else throw new Error(`unknown argument: ${argument}`)
  }
  return { root, check }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === scriptPath) {
  try {
    const result = await emitWebCatalog(parseArguments(process.argv.slice(2)))
    process.stdout.write(`web extension catalog ${result.state}\n`)
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
    process.exitCode = 1
  }
}
