#!/usr/bin/env node

import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import process from 'node:process'

const args = process.argv.slice(2)
const argValue = flag => {
  const index = args.indexOf(flag)
  return index === -1 ? undefined : args[index + 1]
}

const repoRoot = resolve(fileURLToPath(new URL('..', import.meta.url)))
const extensionsRoot = resolve(argValue('--root') ?? join(repoRoot, 'extensions', 'mk2'))
const ratchetPath = resolve(
  argValue('--ratchet') ?? join(repoRoot, 'scripts', 'mk2-port-ratchet.json'),
)
const GENERATED_MARKER = '@generated by scripts/convert-mk2.mjs'
const PENDING_CODE = 'x3.mk2/port-pending'

const ratchet = JSON.parse(readFileSync(ratchetPath, 'utf8'))
if (ratchet.schemaVersion !== 1 || typeof ratchet.families !== 'object') {
  throw new Error(`invalid MK2 port ratchet: ${ratchetPath}`)
}

const familyDirectories = existsSync(extensionsRoot)
  ? readdirSync(extensionsRoot, { withFileTypes: true })
      .filter(entry => entry.isDirectory())
      .map(entry => entry.name)
      .sort()
  : []
const familyNames = [...new Set([...familyDirectories, ...Object.keys(ratchet.families)])].sort()
const rows = []
const errors = []

for (const family of familyNames) {
  const srcRoot = join(extensionsRoot, family, 'src')
  const codecDirectories = existsSync(srcRoot)
    ? readdirSync(srcRoot, { withFileTypes: true })
        .filter(entry => entry.isDirectory())
        .map(entry => entry.name)
        .sort()
    : []
  let ported = 0
  let pending = 0
  for (const codec of codecDirectories) {
    const modulePath = join(srcRoot, codec, 'codec.js')
    if (!existsSync(modulePath)) continue
    const source = readFileSync(modulePath, 'utf8')
    const generated = source.includes(GENERATED_MARKER)
    const throwsPending = source.includes(PENDING_CODE)
    if (!generated && throwsPending) {
      errors.push(`${family}/${codec}: generated marker is gone but open() is still port-pending`)
    }
    if (generated) {
      if (!throwsPending) {
        errors.push(`${family}/${codec}: generated stub lost its port-pending guard`)
      }
      pending += 1
    } else if (!throwsPending) {
      ported += 1
    } else {
      pending += 1
    }
  }

  const expected = Number(ratchet.families[family] ?? 0)
  if (!Number.isSafeInteger(expected) || expected < 0) {
    errors.push(`${family}: ratchet value must be a non-negative integer`)
  } else if (ported < expected) {
    errors.push(`${family}: port count degraded from ${expected} to ${ported}`)
  } else if (ported > expected) {
    errors.push(`${family}: ratchet is behind (${expected}; current ${ported})`)
  }
  rows.push({ family, total: ported + pending, ported, pending })
}

const widths = {
  family: Math.max('family'.length, ...rows.map(row => row.family.length)),
  total: Math.max('total'.length, ...rows.map(row => String(row.total).length)),
  ported: Math.max('ported'.length, ...rows.map(row => String(row.ported).length)),
  pending: Math.max('pending'.length, ...rows.map(row => String(row.pending).length)),
}
const line = row =>
  `${String(row.family).padEnd(widths.family)}  ${String(row.total).padStart(widths.total)}  ${String(row.ported).padStart(widths.ported)}  ${String(row.pending).padStart(widths.pending)}`
console.log(line({ family: 'family', total: 'total', ported: 'ported', pending: 'pending' }))
for (const row of rows) console.log(line(row))
const totals = rows.reduce(
  (sum, row) => ({
    family: 'TOTAL',
    total: sum.total + row.total,
    ported: sum.ported + row.ported,
    pending: sum.pending + row.pending,
  }),
  { family: 'TOTAL', total: 0, ported: 0, pending: 0 },
)
console.log(line(totals))

if (errors.length > 0) {
  console.error(`MK2 port ratchet failed:\n- ${errors.join('\n- ')}`)
  process.exitCode = 1
}
