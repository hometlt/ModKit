#!/usr/bin/env node

import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { basename, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import process from 'node:process'

import { productExtensionDirectory } from './lib/external-extension-roots.mjs'

const args = process.argv.slice(2)
const argValue = flag => {
  const index = args.indexOf(flag)
  return index === -1 ? undefined : args[index + 1]
}

const repoRoot = resolve(fileURLToPath(new URL('..', import.meta.url)))
const ratchetPath = resolve(
  argValue('--ratchet') ?? join(repoRoot, 'scripts', 'mk2-port-ratchet.json'),
)
const GENERATED_MARKER = '@generated by scripts/convert-mk2.mjs'
const PENDING_CODE = 'x3.mk2/port-pending'
// Groups that hold contract references and author tooling rather than ported codecs.
const UNSCANNED_GROUPS = new Set(['_reference', 'codec-kit'])

const ratchet = JSON.parse(readFileSync(ratchetPath, 'utf8'))
if (ratchet.schemaVersion !== 2 || typeof ratchet.families !== 'object') {
  throw new Error(`invalid MK2 port ratchet: ${ratchetPath}`)
}

const subdirectories = path =>
  existsSync(path)
    ? readdirSync(path, { withFileTypes: true })
        .filter(entry => entry.isDirectory())
        .map(entry => entry.name)
        .sort()
    : []

// A ported codec is ratcheted wherever it lives: relocating a family out of the staging
// area renames its key, it does not retire the guarantee. Group roots are discovered so
// that a new vendor group is covered the moment it appears.
const explicitRoot = argValue('--root')
const groupRoots = new Map(
  (explicitRoot
    ? [resolve(explicitRoot)]
    : subdirectories(join(repoRoot, 'extensions'))
        .filter(group => !UNSCANNED_GROUPS.has(group))
        .map(group => join(repoRoot, 'extensions', group))
  ).map(root => [basename(root), root]),
)

const familySources = new Map()
for (const [group, root] of groupRoots) {
  for (const family of subdirectories(root)) {
    familySources.set(`${group}/${family}`, join(root, family, 'src'))
  }
}
for (const key of Object.keys(ratchet.families)) {
  if (familySources.has(key)) continue
  if (explicitRoot === undefined) {
    // The authored workspace manifest owns legacy-family relocation. This keeps the ratchet
    // neutral: moving Blizzard, Warzone or any future publisher out of the core repository does
    // not require a hardcoded publisher list here, and a missing configured source remains a
    // visible zero below.
    const relocated = productExtensionDirectory(repoRoot, key.split('/'))
    if (existsSync(relocated)) {
      familySources.set(key, join(relocated, 'src'))
      continue
    }
  }
  const groupRoot = groupRoots.get(key.slice(0, key.indexOf('/')))
  // A ratcheted family whose directory is gone still gets a row, and so a visible zero.
  familySources.set(key, groupRoot ? join(groupRoot, key.slice(key.indexOf('/') + 1), 'src') : '')
}

const familyNames = [...familySources.keys()].sort()
const rows = []
const errors = []

for (const family of familyNames) {
  const srcRoot = familySources.get(family)
  const codecDirectories = subdirectories(srcRoot)
  let ported = 0
  let pending = 0
  for (const codec of codecDirectories) {
    const modulePath = join(srcRoot, codec, 'codec.js')
    if (!existsSync(modulePath)) continue
    const source = readFileSync(modulePath, 'utf8')
    const generated = source.includes(GENERATED_MARKER)
    const throwsPending = source.includes(PENDING_CODE)
    if (!generated && throwsPending) {
      errors.push(`${family}/${codec}: generated marker is gone but open() is still port-pending`)
    }
    if (generated) {
      if (!throwsPending) {
        errors.push(`${family}/${codec}: generated stub lost its port-pending guard`)
      }
      pending += 1
    } else if (!throwsPending) {
      ported += 1
    } else {
      pending += 1
    }
  }

  const expected = Number(ratchet.families[family] ?? 0)
  if (!Number.isSafeInteger(expected) || expected < 0) {
    errors.push(`${family}: ratchet value must be a non-negative integer`)
  } else if (ported < expected) {
    errors.push(`${family}: port count degraded from ${expected} to ${ported}`)
  } else if (ported > expected) {
    errors.push(`${family}: ratchet is behind (${expected}; current ${ported})`)
  }
  rows.push({ family, total: ported + pending, ported, pending })
}

const widths = {
  family: Math.max('family'.length, ...rows.map(row => row.family.length)),
  total: Math.max('total'.length, ...rows.map(row => String(row.total).length)),
  ported: Math.max('ported'.length, ...rows.map(row => String(row.ported).length)),
  pending: Math.max('pending'.length, ...rows.map(row => String(row.pending).length)),
}
const line = row =>
  `${String(row.family).padEnd(widths.family)}  ${String(row.total).padStart(widths.total)}  ${String(row.ported).padStart(widths.ported)}  ${String(row.pending).padStart(widths.pending)}`
console.log(line({ family: 'family', total: 'total', ported: 'ported', pending: 'pending' }))
for (const row of rows) console.log(line(row))
const totals = rows.reduce(
  (sum, row) => ({
    family: 'TOTAL',
    total: sum.total + row.total,
    ported: sum.ported + row.ported,
    pending: sum.pending + row.pending,
  }),
  { family: 'TOTAL', total: 0, ported: 0, pending: 0 },
)
console.log(line(totals))

// Per-family rows cannot see a family whose directory and ratchet entry vanish together —
// which is exactly what relocation does. The total is the guard against that: it may rise,
// never fall.
const minimumTotal = Number(ratchet.minimumTotal ?? 0)
if (!Number.isSafeInteger(minimumTotal) || minimumTotal < 0) {
  errors.push('minimumTotal must be a non-negative integer')
} else if (totals.ported < minimumTotal) {
  errors.push(`total port count degraded from ${minimumTotal} to ${totals.ported}`)
} else if (totals.ported > minimumTotal) {
  errors.push(`minimumTotal is behind (${minimumTotal}; current ${totals.ported})`)
}

if (errors.length > 0) {
  console.error(`MK2 port ratchet failed:\n- ${errors.join('\n- ')}`)
  process.exitCode = 1
}
