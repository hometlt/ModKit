#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises'
import process from 'node:process'

const authorityUrl = new URL('../packages/sdk/host-facilities.v1.json', import.meta.url)
const outputUrl = new URL('../packages/sdk/src/host-facilities.generated.ts', import.meta.url)
const check = process.argv.includes('--check')

const authority = JSON.parse(await readFile(authorityUrl, 'utf8'))
const compareUtf8 = (left, right) => Buffer.compare(Buffer.from(left), Buffer.from(right))

function assertList(name, values) {
  if (!Array.isArray(values) || values.some(value => typeof value !== 'string')) {
    throw new TypeError(`${name} must be an array of strings`)
  }
  const sorted = [...new Set(values)].sort(compareUtf8)
  if (JSON.stringify(sorted) !== JSON.stringify(values)) {
    throw new TypeError(`${name} must be unique and sorted in canonical UTF-8 order`)
  }
}

if (authority.schemaVersion !== 1) throw new TypeError('host facility registry must be version 1')
assertList('facilities', authority.facilities)
assertList('legacyAliases', authority.legacyAliases)

const rendered =
  `// Generated by scripts/emit-host-facilities.mjs. Do not edit by hand.\n` +
  `export const STANDARD_HOST_FACILITY_IDS = Object.freeze(${JSON.stringify(authority.facilities, null, 2)} as const)\n\n` +
  `export const LEGACY_HOST_FACILITY_ALIASES = Object.freeze(${JSON.stringify(authority.legacyAliases, null, 2)} as const)\n`

if (check) {
  let existing = ''
  try {
    existing = await readFile(outputUrl, 'utf8')
  } catch {}
  if (existing !== rendered) {
    console.error('facilities:check: generated registry differs; run pnpm facilities:emit')
    process.exit(1)
  }
  console.log(
    `facilities:check: ${authority.facilities.length} standard + ${authority.legacyAliases.length} legacy IDs up to date`,
  )
} else {
  await writeFile(outputUrl, rendered, 'utf8')
  console.log(
    `facilities:emit: wrote ${authority.facilities.length} standard + ${authority.legacyAliases.length} legacy IDs`,
  )
}
