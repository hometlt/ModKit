import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { afterAll, describe, expect, it } from 'vitest'

const scriptsDir = fileURLToPath(new URL('..', import.meta.url))
const checker = join(scriptsDir, 'check-mk2-ports.mjs')
const scratch = mkdtempSync(join(tmpdir(), 'mk2-ports-'))
const root = join(scratch, 'extensions')
const ratchet = join(scratch, 'ratchet.json')
const origins = join(scratch, 'codec-origins.json')
const pendingModule =
  "// @generated by scripts/convert-mk2.mjs\nthrow Object.assign(new Error(), { code: 'x3.mk2/port-pending' })\n"
const portedModule = 'export const abiVersion = 1\n'

afterAll(() => rmSync(scratch, { recursive: true, force: true }))

function modulePath(codec: string, family = 'sample-family'): string {
  const path = join(root, family, 'src', codec, 'codec.js')
  mkdirSync(dirname(path), { recursive: true })
  return path
}

// The scanned group is named after the root directory, so a relocated family is a renamed
// key rather than a retired one.
const key = (family: string) => `extensions/${family}`

function run() {
  if (!existsSync(origins)) {
    writeFileSync(origins, JSON.stringify({ schemaVersion: 1, codecs: [] }))
  }
  return spawnSync(
    process.execPath,
    [checker, '--root', root, '--ratchet', ratchet, '--origins', origins],
    {
      encoding: 'utf8',
    },
  )
}

describe('MK2 port ratchet', () => {
  it('prints progress and rejects regressions, disguised stubs, and stale advances', () => {
    writeFileSync(modulePath('pending'), pendingModule)
    writeFileSync(modulePath('ported'), portedModule)
    writeFileSync(
      ratchet,
      JSON.stringify({
        schemaVersion: 2,
        minimumTotal: 1,
        families: { [key('sample-family')]: 1 },
      }),
    )

    const clean = run()
    expect(clean.status).toBe(0)
    expect(clean.stdout).toContain(key('sample-family'))
    expect(clean.stdout).toMatch(/TOTAL\s+2\s+1\s+1/)

    writeFileSync(modulePath('ported'), pendingModule)
    const degraded = run()
    expect(degraded.status).toBe(1)
    expect(degraded.stderr).toContain('port count degraded from 1 to 0')

    writeFileSync(
      modulePath('ported'),
      "throw Object.assign(new Error(), { code: 'x3.mk2/port-pending' })\n",
    )
    const disguised = run()
    expect(disguised.status).toBe(1)
    expect(disguised.stderr).toContain('generated marker is gone')

    writeFileSync(modulePath('ported'), portedModule)
    writeFileSync(modulePath('second-port'), portedModule)
    const advanced = run()
    expect(advanced.status).toBe(1)
    expect(advanced.stderr).toContain('ratchet is behind (1; current 2)')
  })

  it('rejects a family that disappears together with its ratchet entry', () => {
    rmSync(join(root, 'sample-family'), { recursive: true, force: true })
    writeFileSync(modulePath('kept', 'staying-family'), portedModule)
    writeFileSync(modulePath('moved', 'leaving-family'), portedModule)
    const entries = { [key('staying-family')]: 1, [key('leaving-family')]: 1 }
    writeFileSync(ratchet, JSON.stringify({ schemaVersion: 2, minimumTotal: 2, families: entries }))
    expect(run().status).toBe(0)

    // Removing the directory alone is already visible as a degraded family.
    rmSync(join(root, 'leaving-family'), { recursive: true, force: true })
    const orphaned = run()
    expect(orphaned.status).toBe(1)
    expect(orphaned.stderr).toContain('port count degraded from 1 to 0')

    // Removing its entry in the same breath is the case that used to pass silently.
    writeFileSync(
      ratchet,
      JSON.stringify({
        schemaVersion: 2,
        minimumTotal: 2,
        families: { [key('staying-family')]: 1 },
      }),
    )
    const retired = run()
    expect(retired.status).toBe(1)
    expect(retired.stderr).toContain('total port count degraded from 2 to 1')
  })

  it('uses explicit authored provenance after src/formats is flattened', () => {
    rmSync(root, { recursive: true, force: true })
    writeFileSync(modulePath('ported'), portedModule)
    writeFileSync(modulePath('authored'), portedModule)
    writeFileSync(
      ratchet,
      JSON.stringify({
        schemaVersion: 2,
        minimumTotal: 1,
        families: { [key('sample-family')]: 1 },
      }),
    )
    const origin = {
      family: key('sample-family'),
      codec: 'authored',
      origin: 'authored',
      formerPath: 'extensions/sample-family/src/formats/authored/codec.js',
      currentPath: 'extensions/sample-family/src/authored/codec.js',
    }
    writeFileSync(origins, JSON.stringify({ schemaVersion: 1, codecs: [origin] }))

    const clean = run()
    expect(clean.status, clean.stderr).toBe(0)
    expect(clean.stdout).toMatch(/TOTAL\s+1\s+1\s+0/)

    writeFileSync(
      origins,
      JSON.stringify({
        schemaVersion: 1,
        codecs: [{ ...origin, formerPath: origin.currentPath }],
      }),
    )
    const provenanceLost = run()
    expect(provenanceLost.status).toBe(1)
    expect(provenanceLost.stderr).toContain('must preserve authored formerPath')
  })
})
