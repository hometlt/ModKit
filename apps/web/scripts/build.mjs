/**
 * URL catalogs are trusted by origin, and the trust decision belongs to whoever deploys this
 * build. The page receives no runtime API for changing this list: esbuild substitutes the frozen
 * JSON value into embed.js. A comma-separated environment value keeps CI/deployment wiring plain.
 */
const embedExtensionOrigins = Object.freeze(
  [
    ...new Set(
      (process.env['MODKIT_EMBED_EXTENSION_ORIGINS'] ?? '')
        .split(',')
        .map(value => value.trim())
        .filter(value => value !== '')
        .map(value => {
          let url
          try {
            url = new URL(value)
          } catch {
            throw new TypeError(`invalid MODKIT_EMBED_EXTENSION_ORIGINS entry: ${value}`)
          }
          if (
            (url.protocol !== 'http:' && url.protocol !== 'https:') ||
            url.username !== '' ||
            url.password !== ''
          ) {
            throw new TypeError(`embed extension origin must be an http(s) origin: ${value}`)
          }
          return url.origin
        }),
    ),
  ].sort(),
)

// A clean output every time: hashed chunks and copied artifacts of a previous build must not
// linger next to the current ones (a stale chunk is unreachable but still served).
rmSync(dist, { recursive: true, force: true })
mkdirSync(dist, { recursive: true })

/*
 * Two page entries in one graph. `main.js` is the PWA shell; `embed.js` is the custom-element
 * entry a third-party page loads with a single script tag (`src/embed.ts`). They are built
 * together, with splitting on, so everything both of them use — the ui viewers, the host, the
 * generated catalog — lands in a shared chunk and an embedding page that also happens to open the
 * app downloads it once. Splitting is what makes them one deployment rather than two bundles that
 * merely sit in the same folder.
 */
const shellBuild = await build({
  entryPoints: {
    main: join(appRoot, 'src', 'shell.ts'),
    embed: join(appRoot, 'src', 'embed.ts'),
  },
  outdir: dist,
  bundle: true,
  splitting: true,
  format: 'esm',
  platform: 'browser',
  target: ['chrome120', 'firefox121', 'safari17'],
  chunkNames: 'chunks/[name]-[hash]',
  loader: { '.css': 'css', '.ttf': 'dataurl' },
  absWorkingDir: repoRoot,
  define: {
    __MODKIT_EMBED_EXTENSION_ORIGINS__: JSON.stringify(embedExtensionOrigins),
    __MODKIT_FORMAT_SMOKE_AUTHORITY_SHA256__: JSON.stringify(formatSmokeAuthoritySha256),
  },
  logLevel: 'warning',
  metafile: true,
})

