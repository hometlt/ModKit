// ---------------------------------------------------------------- server
if (process.argv.includes('--serve')) {
  const types = {
    '.html': 'text/html',
    '.js': 'text/javascript',
    '.css': 'text/css',
    '.png': 'image/png',
    '.webmanifest': 'application/manifest+json',
    '.json': 'application/json',
    '.md': 'text/markdown',
    '.mjs': 'text/javascript',
    '.svg': 'image/svg+xml',
    '.csv': 'text/csv',
    '.ini': 'text/plain',
    '.txt': 'text/plain',
    '.woff2': 'font/woff2',
  }
  // `--port <n>`: two checkouts of this lab can be served side by side without fighting over 8732.
  const portIndex = process.argv.indexOf('--port')
  const requested = portIndex === -1 ? undefined : Number(process.argv[portIndex + 1])
  if (
    requested !== undefined &&
    (!Number.isSafeInteger(requested) || requested < 1 || requested > 65_535)
  ) {
    console.error(`invalid --port ${process.argv[portIndex + 1]}`)
    process.exit(1)
  }
  const port = requested ?? 8732
  createServer((request, response) => {
    const url = new URL(request.url ?? '/', `http://localhost:${port}`)
    const name = url.pathname === '/' ? '/index.html' : url.pathname
    const file = join(dist, name)
    if (!file.startsWith(dist) || !existsSync(file)) {
      response.writeHead(404)
      response.end('not found')
      return
    }
    if (request.method !== 'GET' && request.method !== 'HEAD') {
      response.writeHead(405, { Allow: 'GET, HEAD' })
      response.end('method not allowed')
      return
    }
    const size = statSync(file).size
    const commonHeaders = {
      'Content-Type': types[extname(file)] ?? 'application/octet-stream',
      'Accept-Ranges': 'bytes',
      // A service worker may only claim a scope at or below its own path.
      ...(name === '/service-worker.js' ? { 'Service-Worker-Allowed': '/' } : {}),
    }
    const range = request.headers.range
    if (range !== undefined) {
      const match = /^bytes=(\d+)-(\d*)$/u.exec(range)
      const start = match === null ? Number.NaN : Number(match[1])
      const requestedEnd = match?.[2] === '' ? size - 1 : Number(match?.[2])
      const end = Math.min(requestedEnd, size - 1)
      if (
        match === null ||
        !Number.isSafeInteger(start) ||
        !Number.isSafeInteger(requestedEnd) ||
        start < 0 ||
        requestedEnd < start ||
        start >= size
      ) {
        response.writeHead(416, {
          ...commonHeaders,
          'Content-Range': `bytes */${size}`,
          'Content-Length': '0',
        })
        response.end()
        return
      }
      response.writeHead(206, {
        ...commonHeaders,
        'Content-Range': `bytes ${start}-${end}/${size}`,
        'Content-Length': String(end - start + 1),
      })
      if (request.method === 'HEAD') response.end()
      else createReadStream(file, { start, end }).pipe(response)
      return
    }
    response.writeHead(200, { ...commonHeaders, 'Content-Length': String(size) })
    if (request.method === 'HEAD') response.end()
    else createReadStream(file).pipe(response)
  }).listen(port, () => console.log(`serving http://localhost:${port}`))
}
