function assertNoNodeProtocol(result) {
  for (const [input, details] of Object.entries(result.metafile.inputs)) {
    if (details.imports.some(entry => /^node:[A-Za-z]/u.test(entry.path))) {
      throw new Error(`browser bundle imports a Node protocol module from ${input}`)
    }
  }
}
for (const result of [shellBuild, workerBuild]) assertNoNodeProtocol(result)
function assertNoNodeProtocolOutput(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) assertNoNodeProtocolOutput(path)
    else if (
      entry.isFile() &&
      path.endsWith('.js') &&
      /(?:\bfrom\s*['"]|\bimport\(\s*['"])node:[A-Za-z]/u.test(readFileSync(path, 'utf8'))
    ) {
      throw new Error(`browser output contains a Node protocol import: ${path}`)
    }
  }
}
