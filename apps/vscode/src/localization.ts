const catalog = (locale: 'en' | 'ru', messages: Readonly<Record<string, string>>) =>
  parseUiCatalogDocument(
    {
      schema: UI_CATALOG_SCHEMA,
      locale,
      namespace: 'modkit.app.vscode',
      messages,
    },
    {
      authorizedMessagePrefixes: ['vscode.', 'stage.'],
      ...(locale === 'en' ? {} : { fallbackCatalog: EN_MESSAGES }),
    },
  )

export const VSCODE_UI_CATALOGS: readonly UiCatalogDocument[] = Object.freeze([
  catalog('en', EN_MESSAGES),
  catalog('ru', RU_MESSAGES),
])

/** Resolve VS Code's BCP-47 UI language and layer this application's static catalogs over core. */
export function createVscodeLocalizer(
  requested: string | readonly string[] | undefined,
  catalogs: readonly UiCatalogDocument[] = [],
): UiLocalizer {
  const locale = resolveUiLocale(requested, {
    availableLocales: [...VSCODE_UI_CATALOGS, ...catalogs].map(item => item.locale),
    fallbackLocale: 'en',
  })
  return createUiLocalizer(locale, {
    catalogs: [...VSCODE_UI_CATALOGS, ...catalogs],
    fallbackLocale: 'en',
  })
}

/** Validated Extension Manager/VFS catalogs, supplied without importing host code in the UI. */
export type VscodeLocalizationCatalogLoader = () => Promise<{
  readonly catalogs: readonly UiCatalogDocument[]
}>

export async function createVscodeLocalizerFromCatalogLoader(
  requested: string | readonly string[] | undefined,
  loadCatalogs: VscodeLocalizationCatalogLoader,
  catalogs: readonly UiCatalogDocument[] = [],
): Promise<UiLocalizer> {
  const loaded = await loadCatalogs()
  return createVscodeLocalizer(requested, [...catalogs, ...loaded.catalogs])
}
