/**
 * Shipped palettes (UK-1). Static values only — installable theme contributions are UK-3.
 *
 * `modkit-dark` and `modkit-light` are derived from VS Code Dark+/Light+ so a VS Code user meets
 * a familiar surface in the browser and Electron hosts. `modkit-high-contrast` is not optional:
 * BRIEF-13C C-15 makes it an acceptance gate.
 *
 * A palette is a plain value map. The generator fails if any public tier-1 or tier-2 token has no
 * value in every theme, so adding a token forces a decision in all three.
 */

export type ThemeId = 'modkit-dark' | 'modkit-light' | 'modkit-high-contrast'
export type Appearance = 'dark' | 'light'

export interface Palette {
  readonly id: ThemeId
  readonly displayName: string
  readonly appearance: Appearance
  /** Selector stamped on the root element; also drives the prefers-color-scheme default. */
  readonly isDefaultFor?: Appearance
  readonly values: Readonly<Record<string, string>>
}

