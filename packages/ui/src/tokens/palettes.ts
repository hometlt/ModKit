const STEPS = ['050', '100', '200', '300', '400', '500', '600', '700', '800', '900']

function rampValues(overrides: Record<string, readonly string[]> = {}): Record<string, string> {
  const out: Record<string, string> = {}
  for (const [hue, ramp] of Object.entries({ ...RAMPS, ...overrides })) {
    ramp.forEach((value, index) => {
      out[`palette.${hue}.${STEPS[index]}`] = value
    })
  }
  return out
}

