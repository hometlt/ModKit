import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import process from 'node:process'
import { format } from 'prettier'
import ts from 'typescript'

const packageRoot = resolve(import.meta.dirname, '..')
const sourceRoot = join(packageRoot, 'src')
const localizationSource = join(sourceRoot, 'localization', 'index.ts')
const outputPath = join(sourceRoot, 'localization', 'fallback-catalogs.generated.ts')
const check = process.argv.includes('--check')

function evaluateString(node) {
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return node.text
  if (ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.PlusToken) {
    const left = evaluateString(node.left)
    const right = evaluateString(node.right)
    return left === undefined || right === undefined ? undefined : left + right
  }
  return undefined
}

function englishMessages() {
  const text = readFileSync(localizationSource, 'utf8')
  const source = ts.createSourceFile(localizationSource, text, ts.ScriptTarget.Latest, true)
  let object
  const visit = node => {
    if (
      ts.isVariableDeclaration(node) &&
      node.name.getText(source) === 'EN_MESSAGES' &&
      node.initializer !== undefined
    ) {
      const initializer = node.initializer
      object =
        ts.isCallExpression(initializer) && initializer.arguments[0] !== undefined
          ? initializer.arguments[0]
          : initializer
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
  if (object === undefined || !ts.isObjectLiteralExpression(object)) {
    throw new Error('EN_MESSAGES must be an object literal (optionally wrapped in Object.freeze)')
  }
  const messages = new Map()
  for (const property of object.properties) {
    if (!ts.isPropertyAssignment(property)) continue
    const key = ts.isStringLiteral(property.name)
      ? property.name.text
      : property.name.getText(source)
    const value = evaluateString(property.initializer)
    if (value === undefined) throw new Error(`EN_MESSAGES.${key} must be a static string`)
    messages.set(key, value)
  }
  return messages
}

function sourceFiles(directory) {
  const result = []
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) result.push(...sourceFiles(path))
    else if (entry.isFile() && entry.name.endsWith('.ts') && !entry.name.endsWith('.d.ts')) {
      result.push(path)
    }
  }
  return result
}

function catalogName(path) {
  let name = relative(sourceRoot, path).replaceAll('\\', '/').replace(/\.ts$/u, '')
  name = name
    .replace(/\/index$/u, '')
    .replaceAll('/', '_')
    .replaceAll('-', '_')
  return `${name.toUpperCase()}_FALLBACK_MESSAGES`
}

function usedMessageKeys(path, english) {
  const text = readFileSync(path, 'utf8')
  const source = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true)
  const keys = new Set()
  const visit = node => {
    // Message keys are sometimes stored in a typed lookup and passed to `text()` later. Capture
    // those static literals too; values that merely happen to equal a key are harmless fallback
    // bytes and keep this generator independent of TypeScript's full type checker.
    if (ts.isStringLiteralLike(node) && english.has(node.text)) keys.add(node.text)
    if (
      ts.isCallExpression(node) &&
      ts.isPropertyAccessExpression(node.expression) &&
      node.expression.name.text === 'text' &&
      node.arguments[0] !== undefined
    ) {
      const key = node.arguments[0]
      if (ts.isStringLiteralLike(key)) keys.add(key.text)
      else if (ts.isTemplateExpression(key)) {
        const prefix = key.head.text
        for (const candidate of english.keys()) {
          if (candidate.startsWith(prefix)) keys.add(candidate)
        }
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
  return [...keys].sort()
}

const english = englishMessages()
const catalogs = sourceFiles(sourceRoot)
  .filter(path => !path.startsWith(dirname(localizationSource)))
  .map(path => ({ name: catalogName(path), path, keys: usedMessageKeys(path, english) }))
  .filter(catalog => catalog.keys.length > 0)
  .sort((left, right) => left.name.localeCompare(right.name))

const lines = [
  '/* Generated by scripts/generate-localization-fallbacks.mjs. Do not edit by hand. */',
  "import type { UiMessageCatalog } from './index.js'",
  '',
]
for (const catalog of catalogs) {
  lines.push(`export const ${catalog.name} = {`)
  for (const key of catalog.keys) {
    const value = english.get(key)
    if (value === undefined) {
      throw new Error(`${relative(packageRoot, catalog.path)} uses unknown UI message ${key}`)
    }
    lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  }
  lines.push('} as const satisfies UiMessageCatalog', '')
}
const output = await format(`${lines.join('\n')}\n`, {
  parser: 'typescript',
  singleQuote: true,
  semi: false,
  trailingComma: 'all',
  tabWidth: 2,
  arrowParens: 'avoid',
  printWidth: 100,
})

if (check) {
  const current = readFileSync(outputPath, 'utf8')
  if (current !== output) {
    throw new Error('fallback-catalogs.generated.ts is stale; run pnpm localization:emit')
  }
} else {
  writeFileSync(outputPath, output, 'utf8')
  console.log(`wrote ${catalogs.length} surface fallback catalogs`)
}
