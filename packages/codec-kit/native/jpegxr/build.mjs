// Builds the JPEG XR decoder WASM from the vendored jxrlib sources (PROVENANCE.json) and the Modkit
// shim modkit_jxr.c, and writes it, base64-encoded, to src/lib/jpegxr/wasm.ts: the package's tsc
// then carries it into dist, and Node and the web worker load it without fetching an asset.
//
//   EMSDK=<emsdk root> [MODKIT_TEMP=<scratch root>] node native/jpegxr/build.mjs
//
// Needs Emscripten (emsdk); the build records the emcc version it used in the generated module.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const here = import.meta.dirname
const emsdk = process.env.EMSDK
if (!emsdk) throw new Error('set EMSDK to the emsdk root (it holds upstream/emscripten/emcc)')
const emcc = join(emsdk, 'upstream', 'emscripten', process.platform === 'win32' ? 'emcc.exe' : 'emcc')
const env = { ...process.env, EM_CONFIG: join(emsdk, '.emscripten') }

// The decoder and the glue jxrlib's container reader links against; the encoder is linked only
// because JXRGlue.c references it, and nothing exports it.
const sources = [
  'image/sys/adapthuff.c',
  'image/sys/image.c',
  'image/sys/strcodec.c',
  'image/sys/strPredQuant.c',
  'image/sys/strTransform.c',
  'image/sys/perfTimerANSI.c',
  'image/decode/decode.c',
  'image/decode/postprocess.c',
  'image/decode/segdec.c',
  'image/decode/strdec.c',
  'image/decode/strInvTransform.c',
  'image/decode/strPredQuantDec.c',
  'image/decode/JXRTranscode.c',
  'image/encode/encode.c',
  'image/encode/segenc.c',
  'image/encode/strenc.c',
  'image/encode/strFwdTransform.c',
  'image/encode/strPredQuantEnc.c',
  'jxrgluelib/JXRGlue.c',
  'jxrgluelib/JXRGlueJxr.c',
  'jxrgluelib/JXRGluePFC.c',
  'jxrgluelib/JXRMeta.c',
].map(file => join(here, 'jxrlib', file))

const work = mkdtempSync(join(process.env.MODKIT_TEMP ?? tmpdir(), 'modkit-jpegxr-'))
try {
  const output = join(work, 'jpegxr.js')
  execFileSync(
    emcc,
    [
      '-O2',
      '-D__ANSI__',
      '-DDISABLE_PERF_MEASUREMENT',
      `-I${join(here, 'jxrlib', 'jxrgluelib')}`,
      `-I${join(here, 'jxrlib', 'common', 'include')}`,
      `-I${join(here, 'jxrlib', 'image', 'sys')}`,
      '-w',
      ...sources,
      join(here, 'modkit_jxr.c'),
      '--no-entry',
      '-sALLOW_MEMORY_GROWTH=1',
      '-sFILESYSTEM=0',
      '-sEXPORTED_FUNCTIONS=["_malloc","_free","_mk_jxr_open","_mk_jxr_info","_mk_jxr_copy","_mk_jxr_close"]',
      '-o',
      output,
    ],
    { env, stdio: 'inherit' },
  )
  const wasm = readFileSync(join(work, 'jpegxr.wasm'))
  const version = execFileSync(emcc, ['--version'], { env })
    .toString()
    .split(/\r?\n/u)[0]
  const sha256 = createHash('sha256').update(wasm).digest('hex')
  writeFileSync(
    join(here, '..', '..', 'src', 'lib', 'jpegxr', 'wasm.ts'),
    `// Generated by native/jpegxr/build.mjs from the vendored jxrlib (see native/jpegxr/PROVENANCE.json).\n` +
      `// ${version}\n` +
      `export const JPEGXR_WASM_SHA256 = '${sha256}'\n` +
      `export const JPEGXR_WASM_BASE64 =\n  '${wasm.toString('base64')}'\n`,
  )
  console.log(`jpegxr.wasm ${wasm.byteLength} bytes, sha256 ${sha256}`)
} finally {
  rmSync(work, { recursive: true, force: true })
}
