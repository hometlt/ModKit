/** A2 packaging candidate: embed the separately built, pinned WASM and retain official ES glue.
 * Only emits deterministic data/declarations; it does not instantiate WASM or expose an operation.
 */
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const native=dirname(fileURLToPath(import.meta.url));
const root=resolve(native,'../..'),build=resolve(process.argv[2]??join(native,'build'));
const output=join(root,'src/lib/obj2voxel');mkdirSync(output,{recursive:true});
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const wasm=readFileSync(join(build,'obj2voxel.wasm')),glue=readFileSync(join(build,'obj2voxel.mjs'));
const built=JSON.parse(readFileSync(join(build,'build-result.json'),'utf8'));
assert.equal(hash(wasm),built.hashes['obj2voxel.wasm']);assert.equal(hash(glue),built.hashes['obj2voxel.mjs']);
writeFileSync(join(output,'obj2voxel.mjs'),glue);
writeFileSync(join(output,'wasm.ts'),`/** Generated by native/obj2voxel/emit-assets.mjs; upstream/runtime notices: native/obj2voxel/notices.\n * Data only: importing this module never instantiates the kernel. */\nexport const OBJ2VOXEL_WASM_SHA256 = '${hash(wasm)}'\nexport const OBJ2VOXEL_WASM_BASE64 = '${wasm.toString('base64')}'\n`);
writeFileSync(join(output,'obj2voxel.d.mts'),`/** Declaration for pinned Emscripten-generated glue; not a public Modkit job interface. */
export interface Obj2VoxelModule {
  readonly HEAPU8: Uint8Array
  readonly HEAPF32: Float32Array
  readonly HEAPU32: Uint32Array
  _malloc(bytes: number): number
  _free(pointer: number): void
  _proof_run(positions: number, colours: number, uvs: number, triangles: number, mode: number, pixels: number, width: number, height: number, resolution: number, maxCells: number, clamp: number): number
  _proof_output(): number
  _proof_count(): number
}
/** Caller is the trusted owner kernel, never a job-provided options object. */
export interface Obj2VoxelFactoryOptions {
  readonly instantiateWasm: (imports: WebAssembly.Imports, receive: (instance: WebAssembly.Instance) => void) => WebAssembly.Exports
  readonly print: (text: string) => void
  readonly printErr: (text: string) => void
}
export default function createModule(options: Obj2VoxelFactoryOptions): Promise<Obj2VoxelModule>
`);
const paths=['src/lib/obj2voxel/obj2voxel.mjs','src/lib/obj2voxel/obj2voxel.d.mts','src/lib/obj2voxel/wasm.ts'];
const provenancePath=join(native,'PROVENANCE.json'),provenance=JSON.parse(readFileSync(provenancePath,'utf8'));
provenance.files=provenance.files.filter(entry=>!paths.includes(entry.path));
for(const path of paths) {
 const bytes=readFileSync(join(root,path));
 provenance.files.push({path,sha256:hash(bytes),bytes:bytes.length,role:path.endsWith('.mjs')?'official-generated-ES-module-glue':path.endsWith('wasm.ts')?'generated-owned-embedded-WASM-data':'first-party-generated-C-ABI-declaration',upstreamPin:provenance.pins['.'],unpatchedSha256:null,generator:'native/obj2voxel/emit-assets.mjs',compiler:provenance.compiler});
}
provenance.generatedArtifact={wasmSha256:hash(wasm),wasmBytes:wasm.length,glueSha256:hash(glue),glueBytes:glue.length,flags:built.flags,linkFlags:built.linkFlags};
provenance.limitations=provenance.limitations.filter(value=>!value.startsWith('Generated assets will'));
provenance.files.sort((a,b)=>a.path.localeCompare(b.path));
writeFileSync(provenancePath,JSON.stringify(provenance,null,2)+'\n');
console.log(JSON.stringify({files:provenance.files.length,generatedArtifact:provenance.generatedArtifact},null,2));
